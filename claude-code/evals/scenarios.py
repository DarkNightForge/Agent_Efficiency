EXACT = _render(_state(sess_cost=66, sess_cap=300, wk_cost=100, wk_cap=2000,
                       exact=True))

# Tools are disabled, so every task must be answerable from the prompt alone.
# These are framed as PLANNING questions -- which is also where budget awareness
# actually shows up, since that is where scope gets chosen. An earlier version
# asked the model to audit "this repository" while cwd was an empty temp dir;
# the model correctly reported there was nothing there, and the eval measured
# nothing at all (2026-08-17).
# The pre-E10 wording, kept as a CONTROL so the A/B can be re-run at any n.
# It lives here rather than behind a flag in the renderer: a legacy code path
# that ships forever to serve one experiment is worse than a fixture.
def _legacy_binding(block: str) -> str:
    """Rewrite the promoted directive back into the old buried advisory form."""
    lines = [l for l in block.split("\n") if not l.startswith("WOULD RUN OUT")]
    legacy = ("WOULD RUN OUT: week caps in ~2h 42m at this burn, then you are "
              "BLOCKED ~129h 18m until it resets. Worth reshaping the work — say "
              "so before starting, and pace against this allowance, not the others.")
    out = []
    for line in lines:
        out.append(line)
        if line.startswith("Burn:"):
            out.append(legacy)
    return "\n".join(out)


